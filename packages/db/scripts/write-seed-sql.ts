/**
 * Writes supabase/seed.sql from the same deterministic generator the demo uses,
 * so the database and the in-browser demo hold identical fictional data.
 * Run: pnpm seed:sql   (optionally SEED_DATE=2026-11-20)
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { generateDataset } from "../src/seed/generate";
import { nassauNow } from "../src/time";

const now = nassauNow();
const ds = generateDataset(process.env.SEED_DATE ?? now.date, process.env.SEED_DATE ? 24 * 60 : now.minutes);
const q = (v: unknown) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(",")}]::text[]`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const out: string[] = ["-- Generated by packages/db/scripts/write-seed-sql.ts — fictional demo data", "begin;"];

for (const a of ds.airlines) {
  out.push(`insert into core.airlines values (${[a.code, a.name, a.terminal, a.colour].map(q).join(",")},${arr(a.aircraft)},${a.sla.counter},${a.sla.gate},${a.sla.jetBridge},${a.sla.lead},${a.sla.supervisor},${a.slaConfirmed},${a.usesJetBridge},${arr(a.requiredTraining)},${json(a.stationManager)},now());`);
}
for (const p of ds.people) {
  out.push(`insert into core.people (id, staff_no, first_name, last_name, role, home_terminal, core_airline, trained_airlines, phone, hire_year) values (${[p.id, p.staffNo, p.firstName, p.lastName, p.role, p.homeTerminal, p.coreAirline].map(q).join(",")},${arr(p.trainedAirlines)},${q(p.phone)},${p.hireYear});`);
  for (const t of p.training) out.push(`insert into core.training_records (person_id, airline, course, completed, expires) values (${[p.id, t.airline, t.course, t.completed, t.expires].map(q).join(",")});`);
}
for (const f of ds.flights) {
  out.push(`insert into core.flights values (${[f.id, f.date, f.airline, f.flightNo, f.destination, f.destinationName, f.aircraft, f.std, f.sta, f.gate, f.terminal].map(q).join(",")},${f.paxBooked},'schedule');`);
}
const rows = ds.roster.map((r) => `(${q(r.personId)},${q(r.date)},${q(r.shift)})`);
for (let i = 0; i < rows.length; i += 500) out.push(`insert into gateline.roster_entries (person_id, date, shift) values ${rows.slice(i, i + 500).join(",")};`);
for (const g of ds.gateLogs) {
  out.push(`insert into gateline.gate_logs (id, flight_id, date, airline, lead_id, team, events, pax_boarded, delay_minutes, delay_cause, status, filed_at, source) values (${[g.id, g.flightId, g.date, g.airline, g.leadId].map(q).join(",")},${json(g.team)},${json(g.events)},${q(g.paxBoarded)},${g.delayMinutes},${q(g.delayCause)},${q(g.status)},${q(g.filedAt)},'seed');`);
  for (const d of g.discrepancies) out.push(`insert into gateline.discrepancies (gate_log_id, type, note, at) values (${[g.id, d.type, d.note, d.at].map(q).join(",")});`);
}
for (const f of ds.feedback) {
  out.push(`insert into gateline.feedback values (${[f.id, f.date, f.airline, f.flightId, f.kind, f.from, f.summary].map(q).join(",")},${arr(f.personIds)},${q(f.status)});`);
}
out.push("commit;");
const target = resolve(import.meta.dirname, "../../../supabase/seed.sql");
writeFileSync(target, out.join("\n") + "\n");
console.log(`seed.sql: ${ds.people.length} people, ${ds.flights.length} flights, ${ds.roster.length} roster entries, ${ds.gateLogs.length} gate logs`);
